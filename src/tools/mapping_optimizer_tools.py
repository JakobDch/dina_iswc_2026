@tool
def edit_mapping(
    dataset: str,
    old_string: str,
    new_string: str,
    replace_all: bool = False,
) -> str:
    """
    Replace a string in the mapping file.

    Use this for ANY modification to the mapping file:
    - IRI templates (rr:template)
    - SQL queries (rr:sqlQuery)
    - Table names, column names, etc.

    Args:
        dataset: Dataset ID (e.g., "trn-large", "edu")
        old_string: The exact string to replace
        new_string: The replacement string
        replace_all: If True, replace ALL occurrences. If False (default), old_string must be unique.

    Returns:
        JSON with:
        - success: True/False
        - replacements: Number of replacements made
        - requires_restart: Whether OnTop needs restart
        - error: Error message if failed
    """
    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    # Backup before modification
    context = get_mapping_context()
    context.backup_mapping(str(mapping_path), dataset)

    try:
        content = mapping_path.read_text(encoding="utf-8")

        # Check if old_string exists
        if old_string not in content:
            old_short = old_string.replace("\n", "\\n")[:150]
            logger.warning(f"edit_mapping [{dataset}] FAILED: old_string not found: '{old_short}'")
            return json.dumps({
                "success": False,
                "error": "old_string not found in mapping file",
            })

        count = content.count(old_string)

        # If not replace_all, check uniqueness
        if not replace_all and count > 1:
            old_short = old_string.replace("\n", "\\n")[:150]
            logger.warning(f"edit_mapping [{dataset}] FAILED: not unique ({count}x): '{old_short}'")
            return json.dumps({
                "success": False,
                "error": f"old_string appears {count} times. Use replace_all=True to replace all, or include more context to make it unique.",
            })

        # Perform the replacement
        if replace_all:
            new_content = content.replace(old_string, new_string)
        else:
            new_content = content.replace(old_string, new_string, 1)

        # Write the modified mapping
        mapping_path.write_text(new_content, encoding="utf-8")
        context.mark_modified()

        old_short = old_string.replace("\n", "\\n")[:150]
        new_short = new_string.replace("\n", "\\n")[:150]
        logger.info(f"edit_mapping [{dataset}] replace_all={replace_all} count={count}: '{old_short}' -> '{new_short}'")

        return json.dumps({
            "success": True,
            "replacements": count,
            "requires_restart": True,
        })

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Mapping modification failed: {str(e)}",
        })


