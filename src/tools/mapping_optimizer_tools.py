@tool
def analyze_mapping_entities(dataset: str) -> str:
    """
    Analyze all entity types in an R2RML mapping and their IRI patterns.

    This is the first step before optimization - it shows:
    - What entities exist in the mapping
    - How their IRIs are constructed (which variables)
    - How many TriplesMaps use each entity (as subject or object)

    This works for ANY dataset - no dataset-specific knowledge required.

    Args:
        dataset: Dataset ID (e.g., "edu", "trn-large", "nrg")

    Returns:
        JSON with list of entities, their variables, and usage counts.
    """
    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    try:
        parser = R2RMLParser(mapping_path)
        entities = parser.get_entity_info()

        return json.dumps({
            "success": True,
            "dataset": dataset,
            "mapping_file": str(mapping_path),
            "total_triples_maps": len(parser.triples_maps),
            "entity_types": len(entities),
            "entities": entities,
        }, indent=2)

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Analysis failed: {str(e)}",
        })


@tool
def analyze_iri_dependencies(
    dataset: str,
    variable: str,
) -> str:
    """
    Analyze all templates that use a specific variable.

    Use this to understand which TriplesMaps would need to be updated
    if you want to change templates using this variable.

    Args:
        dataset: Dataset ID
        variable: Variable name used in templates (e.g., "nr", "trip_id")

    Returns:
        JSON with all subject and object maps using this variable.
    """
    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    try:
        parser = R2RMLParser(mapping_path)
        usages = parser.find_templates_with_variable(variable)

        return json.dumps({
            "success": True,
            "dataset": dataset,
            "variable": variable,
            "subject_map_count": len(usages['subject_maps']),
            "object_map_count": len(usages['object_maps']),
            "total_usages": usages['total'],
            "subject_maps": usages['subject_maps'],
            "object_maps": usages['object_maps'],
        }, indent=2)

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Analysis failed: {str(e)}",
        })


@tool
def optimize_entity_iri(
    dataset: str,
    old_template: str,
    new_template: str,
) -> str:
    """
    Replace an IRI template with a new one across ALL usages in the mapping.

    This ensures IRI consistency by finding and replacing the template
    everywhere it appears (both as subject and object).

    IMPORTANT: The templates must match EXACTLY. Use analyze_mapping_entities
    first to see the exact templates used.

    Args:
        dataset: Dataset ID (e.g., "edu-large", "trn-large")
        old_template: The exact current IRI template to replace
        new_template: The new IRI template to use

    Returns:
        JSON with update results.
    """
    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    # Backup before modification
    context = get_mapping_context()
    context.backup_mapping(str(mapping_path), dataset)

    try:
        content = mapping_path.read_text(encoding="utf-8")

        # Check if old_template exists in the file
        search_pattern = f'rr:template "{old_template}"'
        if search_pattern not in content:
            return json.dumps({
                "success": False,
                "error": f"Template not found in mapping: {old_template}",
            })

        # VALIDATION: Check if new template variables are available in all affected TriplesMaps
        try:
            parser = R2RMLParser(mapping_path)
            validation = parser.validate_template_variables(old_template, new_template)

            if not validation["valid"]:
                # New variables are not available in some source queries
                error_details = []
                for err in validation["errors"]:
                    error_details.append(
                        f"TriplesMap '{err['triples_map']}': missing columns {err['missing_variables']} "
                        f"(available: {err['available_columns'][:10]}...)"
                    )
                return json.dumps({
                    "success": False,
                    "error": "Template validation failed: new variables not available in source queries",
                    "validation_errors": error_details,
                    "added_variables": validation.get("added_variables", []),
                    "hint": (
                        "The new template uses variables that don't exist in all affected SQL queries. "
                        "For mappings with JOINs, you can only use columns that appear in the SELECT clause. "
                        "Consider using the existing columns or skip optimizing this particular template."
                    ),
                })
        except Exception as e:
            # Validation failed - log warning but continue (OnTop will catch errors on restart)
            logger.warning(f"Template validation failed (continuing anyway): {e}")

        # Count occurrences before replacement
        count = content.count(search_pattern)

        # Replace all occurrences
        new_pattern = f'rr:template "{new_template}"'
        modified_content = content.replace(search_pattern, new_pattern)

        # Write modified content
        mapping_path.write_text(modified_content, encoding="utf-8")
        context.mark_modified()

        # Verify syntax
        verify_result = json.loads(verify_mapping_syntax.invoke({"dataset": dataset}))
        if not verify_result.get("valid", False):
            # Rollback on syntax error
            mapping_path.write_text(content, encoding="utf-8")
            return json.dumps({
                "success": False,
                "error": f"Mapping syntax invalid after modification: {verify_result.get('error')}",
                "rolled_back": True,
            })

        # NOTE: OnTop restart is now handled by the SPARQL Agent after all changes are complete
        # This allows batching multiple template changes without waiting for restarts

        return json.dumps({
            "success": True,
            "old_template": old_template,
            "new_template": new_template,
            "replacements": count,
            "requires_restart": True,  # Signal that OnTop needs restart
        }, indent=2)

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Optimization failed: {str(e)}",
        })


