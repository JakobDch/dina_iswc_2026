@dataclass
class MappingOptimizerResult:
    """Result from the Mapping Optimizer Agent.

    The `can_help` field indicates whether the agent identified mapping issues
    that it could fix. If False, the SPARQL Agent should try Multi-Step instead.

    The `requires_restart` field indicates whether OnTop needs to be restarted
    to apply mapping changes. The SPARQL Agent handles the restart after receiving
    this result, allowing multiple changes to be batched before a single restart.
    """
    success: bool
    can_help: bool = True  # False if agent determines mapping optimization won't help
    optimized_tables: list[str] = field(default_factory=list)
    changes_made: list[MappingChange] = field(default_factory=list)
    requires_restart: bool = False  # True if mapping was modified and OnTop needs restart
    error: str | None = None
    reasoning: str = ""
    analysis: str = ""  # SQL analysis explanation (especially when can_help=False)
    identified_issues: list[str] = field(default_factory=list)  # What issues were found

    def to_dict(self) -> dict:
        """Convert to dictionary for JSON serialization."""
        return {
            "success": self.success,
            "can_help": self.can_help,
            "optimized_tables": self.optimized_tables,
            "changes_made": [
                {
                    "table": c.table,
                    "old_template": c.old_template,
                    "new_template": c.new_template,
                    "primary_key_columns": c.primary_key_columns,
                    "old_template_columns": c.old_template_columns,
                    "sql_before": c.sql_before,
                    "sql_after": c.sql_after,
                }
                for c in self.changes_made
            ],
            "requires_restart": self.requires_restart,
            "error": self.error,
            "reasoning": self.reasoning,
            "analysis": self.analysis,
            "identified_issues": self.identified_issues,
        }


