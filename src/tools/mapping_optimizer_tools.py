def _get_mapping_path(dataset: str) -> Path | None:
    """Get the path to the mapping file for a dataset.

    When USE_SLOT_CONTAINERS is enabled and a slot_id is set in context,
    returns the slot-specific mapping path. Otherwise, returns the shared
    mapping path from MAPPINGS_DIR_ROOT.
    """
    dataset_lower = dataset.lower()

    # Build the full dataset name with size suffix if needed
    # Datasets with size variants: edu, trn, nrg
    SIZED_DATASETS = {"edu", "trn", "nrg"}
    base_dataset = dataset_lower.replace('-small', '').replace('-large', '').replace('_small', '').replace('_large', '')
    has_size = any(s in dataset_lower for s in ['-small', '-large', '_small', '_large'])

    if base_dataset in SIZED_DATASETS and not has_size:
        size = get_dataset_size()
        full_dataset = f"{base_dataset}-{size}"
    else:
        full_dataset = dataset_lower

    # Check for slot-specific mapping path first (if slots are enabled)
    slot_id = get_slot_id()
    if USE_SLOT_CONTAINERS and slot_id is not None:
        slot_mappings_dir = MAPPINGS_DIR_ROOT.parent / "mappings-slots" / f"slot{slot_id}"

        # Convention: mappings-slots/slot{N}/{dataset}/mapping.ttl
        slot_mapping_path = slot_mappings_dir / full_dataset / "mapping.ttl"
        if slot_mapping_path.exists():
            return slot_mapping_path

        # Try with underscores instead of hyphens
        slot_mapping_path = slot_mappings_dir / full_dataset.replace("-", "_") / "mapping.ttl"
        if slot_mapping_path.exists():
            return slot_mapping_path

        # Try other common names
        for name in ["mapping.ttl", "ontop.obda", "mapping.obda"]:
            slot_mapping_path = slot_mappings_dir / full_dataset / name
            if slot_mapping_path.exists():
                return slot_mapping_path

    # Fallback to shared mapping (original behavior)
    # Convention: mappings/{dataset}/mapping.ttl
    mapping_path = MAPPINGS_DIR_ROOT / full_dataset / "mapping.ttl"
    if mapping_path.exists():
        return mapping_path

    # Try with underscores instead of hyphens
    mapping_path = MAPPINGS_DIR_ROOT / full_dataset.replace("-", "_") / "mapping.ttl"
    if mapping_path.exists():
        return mapping_path

    # Try other common names
    for name in ["mapping.ttl", "ontop.obda", "mapping.obda"]:
        mapping_path = MAPPINGS_DIR_ROOT / full_dataset / name
        if mapping_path.exists():
            return mapping_path

    return None


