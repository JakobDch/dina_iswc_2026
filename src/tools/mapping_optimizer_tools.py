@tool
def grep_mapping(
    pattern: str,
    dataset: str,
) -> str:
    """
    Search the R2RML mapping file for a pattern. Returns line numbers and matched lines.

    Use this to find where something is in the mapping file. Then use read_mapping()
    with line_start/line_end to read the context you need.

    Args:
        pattern: Search pattern (case-insensitive substring match)
        dataset: Dataset ID (e.g., "trn", "edu")

    Returns:
        JSON with:
        - success: True/False
        - matches: List of {line_number, matched_line} for each match
        - total_lines: Total lines in the file (so you know the range for read_mapping)
        - mapping_file: Path to the mapping file
    """
    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    try:
        lines = mapping_path.read_text(encoding="utf-8").splitlines()
        pattern_lower = pattern.lower()

        matches = []
        for i, line in enumerate(lines):
            if pattern_lower in line.lower():
                matches.append({
                    "line_number": i + 1,
                    "matched_line": line.strip(),
                })

        return json.dumps({
            "success": True,
            "matches": matches,
            "total_lines": len(lines),
            "mapping_file": str(mapping_path),
        }, indent=2)

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Search failed: {str(e)}",
        })


@tool
def read_mapping(
    dataset: str,
    line_start: int | None = None,
    line_end: int | None = None,
) -> str:
    """
    Read the R2RML mapping file for a dataset.

    Use this to read the full mapping or specific line ranges after using grep_mapping.

    Args:
        dataset: Dataset ID (e.g., "trn-large", "edu")
        line_start: Optional start line (1-indexed). If not provided, reads from beginning.
        line_end: Optional end line (1-indexed). If not provided, reads to end.

    Returns:
        JSON with:
        - success: True/False
        - content: The mapping file content (or specified lines)
        - mapping_file: Path to the mapping file
        - total_lines: Total number of lines in the file
    """
    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    try:
        lines = mapping_path.read_text(encoding="utf-8").splitlines()
        total_lines = len(lines)

        # Apply line range if specified
        if line_start is not None or line_end is not None:
            start_idx = (line_start - 1) if line_start else 0
            end_idx = line_end if line_end else total_lines
            lines = lines[start_idx:end_idx]
            # Add line numbers for context
            content = "\n".join(f"{start_idx + i + 1}: {line}" for i, line in enumerate(lines))
        else:
            content = "\n".join(lines)

        return json.dumps({
            "success": True,
            "content": content,
            "mapping_file": str(mapping_path),
            "total_lines": total_lines,
        })

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Failed to read mapping: {str(e)}",
        })




