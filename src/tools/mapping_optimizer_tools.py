@tool
def validate_template_variables(dataset: str) -> str:
    """
    Validate that all template variables exist in the corresponding SQL queries.

    This checks for the common error:
    "The placeholder(s) X in the target do(es) not occur in source query"

    For each TriplesMap, extracts all {variable} placeholders from templates
    and verifies they exist as column aliases in the SQL SELECT clause.

    Args:
        dataset: Dataset ID

    Returns:
        JSON with:
        - success: True/False
        - valid: True if all variables are present in SQL
        - errors: List of missing variable errors
        - warnings: List of potential issues
    """
    import re

    mapping_path = _get_mapping_path(dataset)
    if not mapping_path or not mapping_path.exists():
        return json.dumps({
            "success": False,
            "error": f"Mapping file not found for dataset: {dataset}",
        })

    try:
        content = mapping_path.read_text(encoding="utf-8")
        errors = []
        warnings = []

        # Find all TriplesMap blocks
        # Pattern: <#Name> or <URI> followed by content until the closing .
        triplesmap_pattern = r'(<#?\w+>|<[^>]+>)\s*(?:a\s+rr:TriplesMap\s*[;.])?(.+?)(?=<#|\Z)'
        blocks = re.findall(triplesmap_pattern, content, re.DOTALL)

        for block_name, block_content in blocks:
            # Skip if this doesn't look like a TriplesMap
            if 'rr:logicalTable' not in block_content and 'rr:tableName' not in block_content:
                continue

            # Extract SQL query or table name
            sql_match = re.search(r'rr:sqlQuery\s*"""(.+?)"""', block_content, re.DOTALL)
            table_match = re.search(r'rr:tableName\s*"([^"]+)"', block_content)

            if sql_match:
                sql = sql_match.group(1)
                # Extract column aliases from SELECT clause
                # Pattern: column AS alias or just column
                select_match = re.search(r'SELECT\s+(.+?)\s+FROM', sql, re.IGNORECASE | re.DOTALL)
                if select_match:
                    select_clause = select_match.group(1)
                    # Find all aliases: "X AS alias" or just column names
                    aliases = set()
                    # Match "something AS alias"
                    for match in re.finditer(r'\bAS\s+(\w+)', select_clause, re.IGNORECASE):
                        aliases.add(match.group(1).lower())
                    # Also match simple column names without AS
                    for match in re.finditer(r'(?:^|,)\s*(\w+)\s*(?:,|$)', select_clause):
                        aliases.add(match.group(1).lower())
                else:
                    aliases = set()
            elif table_match:
                # If using rr:tableName, all columns of that table are available
                # We can't easily validate this without DB access, so skip
                continue
            else:
                continue

            # Extract ALL template variables from this block (subject AND object templates)
            template_vars = set()
            for template_match in re.finditer(r'rr:template\s*"([^"]+)"', block_content):
                template = template_match.group(1)
                # Find all {variable} placeholders
                for var_match in re.finditer(r'\{(\w+)\}', template):
                    template_vars.add(var_match.group(1).lower())

            # Check if all template variables exist in SQL aliases
            for var in template_vars:
                if var not in aliases:
                    errors.append({
                        "triplesmap": block_name,
                        "variable": var,
                        "available_aliases": sorted(aliases),
                        "message": f"Variable '{{{var}}}' in template not found in SQL. Available: {sorted(aliases)}"
                    })

        return json.dumps({
            "success": True,
            "valid": len(errors) == 0,
            "error_count": len(errors),
            "errors": errors[:10],  # Limit to first 10 errors
            "warnings": warnings,
        })

    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Validation failed: {str(e)}",
        })


