@tool
def get_table_schema(
    table_name: str,
    dataset: str,
) -> str:
    """
    Get the full schema for a database table: columns, primary keys, and foreign keys.

    Use this to understand the structure of a table before optimizing mappings.
    Foreign key information is essential for understanding cross-table relationships.
    When an object template references an entity from another table, FKs reveal
    which JOINs are needed to obtain the correct context columns.

    Args:
        table_name: Table name (case-insensitive)
        dataset: Dataset ID (used to determine database connection)

    Returns:
        JSON with:
        - success: True/False
        - table: The table name
        - columns: List of {name, type, is_primary_key}
        - primary_key_columns: List of PK column names
        - foreign_keys: List of {column, references_table, references_column}
        - error: Error message if lookup failed
    """
    settings = get_settings()

    db_name = _get_database_name(dataset)
    if not db_name:
        return json.dumps({
            "success": False,
            "error": f"No database mapping for dataset: {dataset}",
        })

    try:
        import mysql.connector

        conn = mysql.connector.connect(
            host=settings.mysql_host,
            port=settings.mysql_port,
            user=settings.mysql_user,
            password=settings.mysql_password,
            database="information_schema",
        )
        cursor = conn.cursor()

        # 1. Get all columns
        cursor.execute("""
            SELECT COLUMN_NAME, COLUMN_TYPE
            FROM COLUMNS
            WHERE TABLE_SCHEMA = %s
            AND UPPER(TABLE_NAME) = UPPER(%s)
            ORDER BY ORAgentic SPARQLL_POSITION
        """, (db_name, table_name))
        columns_raw = cursor.fetchall()

        if not columns_raw:
            # Check if table/database exists
            cursor.execute("""
                SELECT SCHEMA_NAME FROM SCHEMATA WHERE SCHEMA_NAME = %s
            """, (db_name,))
            if not cursor.fetchone():
                cursor.close()
                conn.close()
                return json.dumps({
                    "success": False,
                    "error": f"Database '{db_name}' does not exist",
                })
            cursor.close()
            conn.close()
            return json.dumps({
                "success": False,
                "error": f"Table '{table_name}' not found in database '{db_name}'",
            })

        # 2. Get primary key columns
        cursor.execute("""
            SELECT COLUMN_NAME
            FROM KEY_COLUMN_USAGE
            WHERE TABLE_SCHEMA = %s
            AND UPPER(TABLE_NAME) = UPPER(%s)
            AND CONSTRAINT_NAME = 'PRIMARY'
            ORDER BY ORAgentic SPARQLL_POSITION
        """, (db_name, table_name))
        pk_columns = [row[0].lower() for row in cursor.fetchall()]

        # 3. Get foreign keys
        cursor.execute("""
            SELECT
                kcu.COLUMN_NAME,
                kcu.REFERENCED_TABLE_NAME,
                kcu.REFERENCED_COLUMN_NAME
            FROM KEY_COLUMN_USAGE kcu
            JOIN TABLE_CONSTRAINTS tc
                ON kcu.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
                AND kcu.TABLE_SCHEMA = tc.TABLE_SCHEMA
                AND kcu.TABLE_NAME = tc.TABLE_NAME
            WHERE kcu.TABLE_SCHEMA = %s
            AND UPPER(kcu.TABLE_NAME) = UPPER(%s)
            AND tc.CONSTRAINT_TYPE = 'FOREIGN KEY'
            AND kcu.REFERENCED_TABLE_NAME IS NOT NULL
            ORDER BY kcu.ORAgentic SPARQLL_POSITION
        """, (db_name, table_name))
        fk_rows = cursor.fetchall()

        cursor.close()
        conn.close()

        # Build columns list with PK flag
        columns = [
            {
                "name": col[0].lower(),
                "type": col[1],
                "is_primary_key": col[0].lower() in pk_columns,
            }
            for col in columns_raw
        ]

        # Build FK list
        foreign_keys = [
            {
                "column": row[0].lower(),
                "references_table": row[1],
                "references_column": row[2].lower(),
            }
            for row in fk_rows
        ]

        return json.dumps({
            "success": True,
            "table": table_name,
            "columns": columns,
            "primary_key_columns": pk_columns,
            "foreign_keys": foreign_keys,
            "database": db_name,
        })

    except ImportError:
        return json.dumps({
            "success": False,
            "error": "mysql-connector-python not installed. Run: pip install mysql-connector-python",
        })
    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Database query failed: {str(e)}",
        })


