class MappingOptimizationContext:
    """Manages temporary mapping changes for a single agent run.

    This context ensures that all mapping changes are reverted when
    the agent run completes (successfully or not).

    When slot_id is set, the context operates on slot-specific mapping files
    and containers, providing isolation for concurrent runs.

    Usage:
        context = MappingOptimizationContext(slot_id=0)  # or None for shared

        # During agent run:
        context.backup_mapping(path, dataset)
        # ... modify mapping ...
        context.mark_modified()

        # At end of agent run:
        context.restore_all()
    """

    def __init__(self, slot_id: int | None = None):
        self.slot_id = slot_id
        self.original_mappings: dict[str, str] = {}  # {path: original_content}
        self.modified: bool = False
        self.affected_datasets: set[str] = set()
        # Initial context parameters for re-reading relevant mapping blocks
        self.initial_mapping_path: str | None = None
        self.initial_reformulated_sql: str | None = None

    def backup_mapping(self, path: str, dataset: str) -> None:
        """Backup a mapping file before modification."""
        if path not in self.original_mappings:
            mapping_path = Path(path)
            if mapping_path.exists():
                self.original_mappings[path] = mapping_path.read_text(encoding="utf-8")
                self.affected_datasets.add(dataset)
                slot_info = f" (slot {self.slot_id})" if self.slot_id is not None else ""
                logger.info(f"Backed up mapping{slot_info}: {path}")

    def mark_modified(self) -> None:
        """Mark that modifications have been made."""
        self.modified = True

    def restore_all(self) -> None:
        """Restore all original mappings and restart affected containers.

        Synchronous implementation to avoid nested event-loop issues.
        When slot_id is set, only restarts the slot-specific containers.
        """
        if not self.original_mappings:
            return

        slot_info = f" (slot {self.slot_id})" if self.slot_id is not None else ""
        logger.info(f"Restoring {len(self.original_mappings)} modified mappings{slot_info}...")

        for path, content in self.original_mappings.items():
            try:
                Path(path).write_text(content, encoding="utf-8")
                logger.info(f"Restored mapping: {path}")
            except Exception as e:
                logger.error(f"Failed to restore mapping {path}: {e}")

        # Restart affected containers (synchronously, slot-aware)
        for dataset in self.affected_datasets:
            try:
                result = restart_ontop_container.invoke({
                    "dataset": dataset,
                    "wait_for_health": True,
                })
                logger.info(f"Container restart for {dataset}{slot_info}: {result}")
            except Exception as e:
                logger.error(f"Failed to restart container for {dataset}: {e}")

        self.original_mappings.clear()
        self.affected_datasets.clear()
        self.modified = False


# Per-task context using ContextVar (thread/async-task local)
# This replaces the global singleton to support concurrent runs with slot isolation
_mapping_context: ContextVar[MappingOptimizationContext | None] = ContextVar(
    "mapping_context", default=None
)


def get_mapping_context() -> MappingOptimizationContext:
    """Get or create the mapping optimization context for the current task.

    The context is task-local (using ContextVar), so each concurrent run
    has its own isolated context with its own slot_id.
    """
    ctx = _mapping_context.get()
    if ctx is None:
        # Create new context with current slot_id from config
        ctx = MappingOptimizationContext(slot_id=get_slot_id())
        _mapping_context.set(ctx)
    return ctx


def reset_mapping_context(slot_id: int | None = None) -> None:
    """Reset the mapping context for a new agent run.

    Args:
        slot_id: The slot ID for this run. If None, uses get_slot_id() from config.
    """
    effective_slot_id = slot_id if slot_id is not None else get_slot_id()
    ctx = MappingOptimizationContext(slot_id=effective_slot_id)
    _mapping_context.set(ctx)


def _cleanup_on_exit() -> None:
    """Cleanup handler called on program exit (including interrupts).

    Ensures mapping modifications are restored even if the program is
    interrupted with Ctrl+C or otherwise terminated.

    Note: With ContextVar, this only cleans up the context in the main thread.
    Each async task should handle its own cleanup via try/finally blocks
    in the orchestrator.
    """
    ctx = _mapping_context.get()
    if ctx is not None and ctx.modified:
        slot_info = f" (slot {ctx.slot_id})" if ctx.slot_id is not None else ""
        logger.info(f"Program exit detected - restoring modified mappings{slot_info}...")
        try:
            ctx.restore_all()
            logger.info("Mapping restoration on exit complete.")
        except Exception as e:
            logger.error(f"Failed to restore mappings on exit: {e}")


# Register cleanup handler for program exit
import atexit
import signal

atexit.register(_cleanup_on_exit)


def _signal_handler(signum, frame):
    """Handle interrupt signals (Ctrl+C) to restore mappings before exit."""
    logger.info(f"Signal {signum} received - cleaning up mappings...")
    _cleanup_on_exit()
    # Re-raise the signal to allow normal termination
    signal.signal(signum, signal.SIG_DFL)
    signal.raise_signal(signum)


# Register signal handlers for graceful cleanup on interrupt
# Only register in main thread (signal handlers don't work in worker threads)
if threading.current_thread() is threading.main_thread():
    signal.signal(signal.SIGINT, _signal_handler)
    signal.signal(signal.SIGTERM, _signal_handler)


