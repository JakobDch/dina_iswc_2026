@tool
def restart_ontop_container(
    dataset: str,
    wait_for_health: bool = True,
) -> str:
    """
    Restart the OnTop container for a dataset to apply mapping changes.

    After modifying a mapping, OnTop must be restarted for changes to take effect.
    This is a synchronous implementation to avoid nested event-loop issues.

    When USE_SLOT_CONTAINERS is enabled and a slot_id is set in context,
    restarts the slot-specific container instead of the shared one.

    Args:
        dataset: Dataset ID
        wait_for_health: Whether to wait for the container to be healthy (default: True)

    Returns:
        JSON with:
        - success: True/False
        - container_name: The container that was restarted
        - healthy: Whether the container is responding (if wait_for_health=True)
        - error: Error message if restart failed
        - slot_id: The slot ID if using slot containers
    """
    import time

    try:
        import docker

        client = docker.from_env()

        # Check for slot-based container naming
        slot_id = get_slot_id()

        # Build the full dataset name with size suffix if needed
        # Datasets with size variants: edu, trn, nrg
        # Datasets without size variants: bsbm, lca
        SIZED_DATASETS = {"edu", "trn", "nrg"}
        base_dataset = dataset.lower().replace('-small', '').replace('-large', '').replace('_small', '').replace('_large', '')

        # Check if dataset already has size suffix
        has_size = any(s in dataset.lower() for s in ['-small', '-large', '_small', '_large'])

        if base_dataset in SIZED_DATASETS and not has_size:
            # Add size suffix from context
            size = get_dataset_size()  # "small" or "large"
            full_dataset = f"{base_dataset}-{size}"
        else:
            full_dataset = dataset

        base_name = full_dataset.replace('-', '_')

        if USE_SLOT_CONTAINERS and slot_id is not None:
            # Slot-specific container: ontop_{dataset}_slot{N}
            container_name = f"ontop_{base_name}_slot{slot_id}"
        else:
            # Shared container: ontop_{dataset}
            container_name = f"ontop_{base_name}"

        try:
            container = client.containers.get(container_name)
        except docker.errors.NotFound:
            return json.dumps({
                "success": False,
                "error": f"Container not found: {container_name}",
                "slot_id": slot_id,
            })

        slot_info = f" (slot {slot_id})" if slot_id is not None else ""
        logger.info(f"Restarting container{slot_info}: {container_name}")
        container.restart(timeout=30)

        if wait_for_health:
            # Wait for container to be healthy by testing actual SPARQL endpoint
            # Note: get_endpoint_for_dataset respects slot_id context automatically
            endpoint = get_endpoint_for_dataset(dataset)

            if endpoint:
                healthy = False
                # Just check if the HTTP endpoint is reachable (no SPARQL query).
                # ASK { ?s ?p ?o } is very expensive on OnTop because it UNIONs all TriplesMaps.
                for attempt in range(30):  # 30 attempts, ~60 seconds total
                    time.sleep(2)
                    try:
                        with httpx.Client(timeout=10) as http_client:
                            response = http_client.get(endpoint)
                            if response.status_code in (200, 400, 404, 406):
                                # 200 = OK, 400/404/406 = endpoint alive but no query provided
                                healthy = True
                                logger.info(f"Container {container_name} SPARQL endpoint ready after {attempt+1} attempts")
                                break
                    except Exception as e:
                        if attempt % 10 == 0:
                            logger.info(f"Health check attempt {attempt+1}: waiting for {container_name}... ({e})")
                        else:
                            logger.debug(f"Health check attempt {attempt+1} failed: {e}")

                if not healthy:
                    logger.warning(f"Container {container_name} did not become healthy after 30 attempts")
                    # Check for container errors (mapping errors, etc.)
                    health_check = check_ontop_container_health(dataset)
                    error_msg = health_check.get("error_message")
                    error_type = health_check.get("error_type")

                    if error_msg:
                        logger.error(f"Container {container_name} error: {error_type} - {error_msg[:200]}")
                        return json.dumps({
                            "success": True,  # Restart was attempted
                            "container_name": container_name,
                            "healthy": False,
                            "error_type": error_type,
                            "error_message": error_msg,
                            "container_status": health_check.get("status"),
                            "slot_id": slot_id,
                        })

                return json.dumps({
                    "success": True,
                    "container_name": container_name,
                    "healthy": healthy,
                    "slot_id": slot_id,
                })

        return json.dumps({
            "success": True,
            "container_name": container_name,
            "slot_id": slot_id,
        })

    except ImportError:
        return json.dumps({
            "success": False,
            "error": "docker package not installed. Run: pip install docker",
        })
    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Container operation failed: {str(e)}",
        })


