# R2RML namespace
RR = "http://www.w3.org/ns/r2rml#"


@dataclass
class TripleMapInfo:
    """Information about a single TriplesMap in the R2RML mapping."""
    uri: str  # Full URI of the TriplesMap
    name: str  # Local name (e.g., "BachelorCandidate")
    subject_template: str | None = None
    subject_column: str | None = None  # For rr:column instead of rr:template
    rdf_classes: list[str] = field(default_factory=list)
    logical_table_name: str | None = None  # For rr:tableName
    logical_table_sql: str | None = None   # For rr:sqlQuery
    predicate_object_maps: list[dict] = field(default_factory=list)  # [{predicate, object_template, object_column}, ...]


class R2RMLParser:
    """
    Generic R2RML parser using rdflib.

    Works for ANY R2RML mapping file, regardless of dataset.
    Parses the mapping as an RDF graph and extracts structural information.
    """

    def __init__(self, mapping_path: Path | str):
        """
        Initialize parser with a mapping file.

        Args:
            mapping_path: Path to the R2RML mapping file (.ttl)
        """
        from rdflib import Graph, Namespace, URIRef
        from rdflib.namespace import RDF

        self.path = Path(mapping_path)
        self.graph = Graph()
        self.graph.parse(str(self.path), format="turtle")

        self.RR = Namespace(RR)
        self.RDF = RDF

        self.triples_maps: dict[str, TripleMapInfo] = {}
        self._parse()

    def _parse(self):
        """Parse the R2RML graph to extract all TriplesMaps."""
        from rdflib import Literal, URIRef, BNode

        # Find all subjects that have rr:logicalTable (these are TriplesMaps)
        for tm_uri in self.graph.subjects(self.RR.logicalTable, None):
            # Get local name from URI
            uri_str = str(tm_uri)
            if '#' in uri_str:
                name = uri_str.split('#')[-1]
            else:
                name = uri_str.split('/')[-1]

            info = TripleMapInfo(uri=uri_str, name=name)

            # Get logical table info
            for lt in self.graph.objects(tm_uri, self.RR.logicalTable):
                # Check for tableName
                for tn in self.graph.objects(lt, self.RR.tableName):
                    info.logical_table_name = str(tn)
                # Check for sqlQuery
                for sq in self.graph.objects(lt, self.RR.sqlQuery):
                    info.logical_table_sql = str(sq)

            # Get subject map info
            for sm in self.graph.objects(tm_uri, self.RR.subjectMap):
                # Get template
                for t in self.graph.objects(sm, self.RR.template):
                    info.subject_template = str(t)
                # Get column (alternative to template)
                for c in self.graph.objects(sm, self.RR.column):
                    info.subject_column = str(c)
                # Get rdf:class(es)
                for cls in self.graph.objects(sm, self.RR["class"]):
                    info.rdf_classes.append(str(cls))

            # Get predicate-object maps
            for pom in self.graph.objects(tm_uri, self.RR.predicateObjectMap):
                po_info = {}

                # Get predicate
                for p in self.graph.objects(pom, self.RR.predicate):
                    po_info['predicate'] = str(p)

                # Get object map
                for om in self.graph.objects(pom, self.RR.objectMap):
                    # Check for template
                    for t in self.graph.objects(om, self.RR.template):
                        po_info['object_template'] = str(t)
                    # Check for column
                    for c in self.graph.objects(om, self.RR.column):
                        po_info['object_column'] = str(c)

                if po_info:
                    info.predicate_object_maps.append(po_info)

            self.triples_maps[name] = info

    def extract_template_variables(self, template: str) -> list[str]:
        """
        Extract variable names from an IRI template.

        Args:
            template: IRI template like "http://example.org/{dept}/{name}"

        Returns:
            List of variable names: ["dept", "name"]
        """
        return re.findall(r'\{([^}]+)\}', template)

    def find_templates_with_variable(self, variable: str) -> dict:
        """
        Find all templates that use a specific variable.

        Args:
            variable: Variable name (e.g., "nr", "trip_id", "name")

        Returns:
            Dictionary with 'subject_maps' and 'object_maps' containing
            all TriplesMaps that use this variable in their templates.
        """
        pattern = '{' + variable + '}'
        subject_maps = []
        object_maps = []

        for name, info in self.triples_maps.items():
            # Check subject template
            if info.subject_template and pattern in info.subject_template:
                subject_maps.append({
                    'triples_map': name,
                    'uri': info.uri,
                    'template': info.subject_template,
                    'variables': self.extract_template_variables(info.subject_template),
                    'rdf_classes': info.rdf_classes,
                    'logical_table': info.logical_table_name or info.logical_table_sql,
                })

            # Check object templates
            for po in info.predicate_object_maps:
                if 'object_template' in po and pattern in po['object_template']:
                    object_maps.append({
                        'triples_map': name,
                        'uri': info.uri,
                        'predicate': po.get('predicate'),
                        'template': po['object_template'],
                        'variables': self.extract_template_variables(po['object_template']),
                    })

        return {
            'subject_maps': subject_maps,
            'object_maps': object_maps,
            'total': len(subject_maps) + len(object_maps),
        }

    def find_all_templates(self) -> dict[str, list[dict]]:
        """
        Get all IRI templates in the mapping, grouped by their variable signature.

        This helps identify which templates represent the same entity type
        (they share the same variables).

        Returns:
            Dictionary mapping variable tuple to list of template usages.
            E.g., {("nr",): [{"type": "subject", "triples_map": "...", ...}]}
        """
        templates_by_vars: dict[tuple, list[dict]] = {}

        for name, info in self.triples_maps.items():
            # Subject template
            if info.subject_template:
                vars_tuple = tuple(sorted(self.extract_template_variables(info.subject_template)))
                if vars_tuple not in templates_by_vars:
                    templates_by_vars[vars_tuple] = []
                templates_by_vars[vars_tuple].append({
                    'type': 'subject',
                    'triples_map': name,
                    'template': info.subject_template,
                    'rdf_classes': info.rdf_classes,
                })

            # Object templates
            for po in info.predicate_object_maps:
                if 'object_template' in po:
                    vars_tuple = tuple(sorted(self.extract_template_variables(po['object_template'])))
                    if vars_tuple not in templates_by_vars:
                        templates_by_vars[vars_tuple] = []
                    templates_by_vars[vars_tuple].append({
                        'type': 'object',
                        'triples_map': name,
                        'predicate': po.get('predicate'),
                        'template': po['object_template'],
                    })

        return templates_by_vars

    def get_entity_info(self) -> list[dict]:
        """
        Analyze the mapping to identify distinct entity types and their IRI patterns.

        Returns a list of entities with:
        - variables: The template variables that identify this entity
        - sample_template: One example template
        - subject_count: How many TriplesMaps use this as subject
        - object_count: How many TriplesMaps reference this as object
        - rdf_classes: What RDF classes are associated
        """
        templates_by_vars = self.find_all_templates()

        entities = []
        for vars_tuple, usages in templates_by_vars.items():
            if not vars_tuple:  # Skip empty variable sets
                continue

            subjects = [u for u in usages if u['type'] == 'subject']
            objects = [u for u in usages if u['type'] == 'object']

            # Collect all RDF classes
            all_classes = []
            for s in subjects:
                all_classes.extend(s.get('rdf_classes', []))

            entities.append({
                'variables': list(vars_tuple),
                'sample_template': usages[0]['template'],
                'subject_count': len(subjects),
                'object_count': len(objects),
                'total_usages': len(usages),
                'rdf_classes': list(set(all_classes)),
                'subject_triples_maps': [s['triples_map'] for s in subjects],
                'object_references': [
                    {'triples_map': o['triples_map'], 'predicate': o.get('predicate')}
                    for o in objects
                ],
            })

        # Sort by total usages (most used first)
        entities.sort(key=lambda e: e['total_usages'], reverse=True)

        return entities

    def validate_template_variables(self, old_template: str, new_template: str) -> dict:
        """
        Validate that all variables in the new template are available in affected TriplesMaps.

        This checks that the source queries (SQL) in all TriplesMaps that use this template
        provide the columns needed for the new template variables.

        Args:
            old_template: The current IRI template being replaced
            new_template: The proposed new IRI template

        Returns:
            Dict with:
            - valid: True if all variables are available
            - errors: List of validation errors (if any)
            - affected_triples_maps: List of affected TriplesMaps with their available columns
        """
        old_vars = set(self.extract_template_variables(old_template))
        new_vars = set(self.extract_template_variables(new_template))
        added_vars = new_vars - old_vars  # Variables that are new

        if not added_vars:
            # No new variables, no validation needed
            return {"valid": True, "errors": [], "affected_triples_maps": []}

        errors = []
        affected = []

        # Find all TriplesMaps using this template
        for name, info in self.triples_maps.items():
            uses_template = False

            # Check subject template
            if info.subject_template == old_template:
                uses_template = True

            # Check object templates
            for po in info.predicate_object_maps:
                if po.get('object_template') == old_template:
                    uses_template = True
                    break

            if not uses_template:
                continue

            # Get available columns from the source
            available_cols = self._extract_available_columns(info)

            affected.append({
                "triples_map": name,
                "source_type": "sql_query" if info.logical_table_sql else "table",
                "source": info.logical_table_sql or info.logical_table_name,
                "available_columns": list(available_cols),
            })

            # Check if all new variables are available
            missing = added_vars - available_cols
            if missing:
                errors.append({
                    "triples_map": name,
                    "missing_variables": list(missing),
                    "available_columns": list(available_cols),
                    "source": info.logical_table_sql or info.logical_table_name,
                })

        return {
            "valid": len(errors) == 0,
            "errors": errors,
            "affected_triples_maps": affected,
            "added_variables": list(added_vars),
        }

    def _extract_available_columns(self, info: "TripleMapInfo") -> set[str]:
        """
        Extract available column names from a TriplesMap's logical table.

        For SQL queries, parses the SELECT clause to find column aliases.
        For table names, returns empty set (would need database introspection).
        """
        available = set()

        if info.logical_table_sql:
            # Parse SQL SELECT clause for column names/aliases
            sql = info.logical_table_sql.upper()

            # Find SELECT ... FROM
            select_match = re.search(r'SELECT\s+(.+?)\s+FROM', sql, re.IGNORECASE | re.DOTALL)
            if select_match:
                select_clause = select_match.group(1)

                # Split by comma, handling nested parentheses
                # Simple approach: split by comma and extract aliases
                parts = re.split(r',\s*(?![^()]*\))', select_clause)

                for part in parts:
                    part = part.strip()
                    # Check for AS alias
                    as_match = re.search(r'\s+AS\s+(\w+)\s*$', part, re.IGNORECASE)
                    if as_match:
                        available.add(as_match.group(1).lower())
                    else:
                        # No alias - use column name (last identifier)
                        # Handle table.column
                        col_match = re.search(r'(?:^|\.)(\w+)\s*$', part)
                        if col_match:
                            available.add(col_match.group(1).lower())

        elif info.logical_table_name:
            # For simple table names, we could query the DB for columns
            # But that requires a DB connection. For now, assume all columns available
            # The actual validation will happen when OnTop tries to start
            pass

        return available


