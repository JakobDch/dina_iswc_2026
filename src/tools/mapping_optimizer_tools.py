@tool
def analyze_sql_for_self_joins(
    sparql_query: str,
    dataset: str,
) -> str:
    """
    Analyze the SQL generated by OnTop for a SPARQL query to detect self-joins.

    Uses the /ontop/reformulate endpoint to get the SQL translation,
    then analyzes it for self-join patterns.

    Args:
        sparql_query: The SPARQL query to analyze
        dataset: Dataset ID (e.g., "trn-large", "edu")

    Returns:
        JSON with:
        - success: True/False
        - has_self_join: Whether self-joins were detected
        - self_join_tables: List of tables with self-joins
        - self_join_pattern: The detected pattern (e.g., "FROM STOP_TIMES v1, STOP_TIMES v2")
        - generated_sql: The full SQL query (truncated if very long)
        - error: Error message if analysis failed
    """
    endpoint = get_endpoint_for_dataset(dataset)
    if not endpoint:
        return json.dumps({
            "success": False,
            "error": f"Unknown dataset: {dataset}",
        })

    # Build reformulate URL from SPARQL endpoint
    # e.g., http://localhost:8082/sparql -> http://localhost:8082/ontop/reformulate
    reformulate_url = endpoint.replace("/sparql", "/ontop/reformulate")

    try:
        with httpx.Client(timeout=REFORMULATE_TIMEOUT) as client:
            response = client.get(
                reformulate_url,
                params={"query": sparql_query},
            )

            if response.status_code != 200:
                return json.dumps({
                    "success": False,
                    "error": f"Reformulate API returned {response.status_code}: {response.text[:500]}",
                })

            sql_output = response.text

            # Use sqlglot-based AST analysis (with regex fallback)
            from src.tools.sql_analyzer import detect_self_joins

            self_joins = detect_self_joins(sql_output)
            self_join_tables = list(self_joins.keys())

            # Build display pattern from first detected self-join
            pattern_display = ""
            if self_joins:
                table, aliases = next(iter(self_joins.items()))
                pattern_display = f"FROM {table} {aliases[0]}, {table} {aliases[1]}"

            return json.dumps({
                "success": True,
                "has_self_join": len(self_join_tables) > 0,
                "self_join_tables": self_join_tables,
                "self_join_pattern": pattern_display,
                "generated_sql": sql_output[:2000] + ("..." if len(sql_output) > 2000 else ""),
            }, indent=2)

    except httpx.TimeoutException:
        return json.dumps({
            "success": False,
            "error": f"Reformulate API timed out after {REFORMULATE_TIMEOUT}s",
        })
    except Exception as e:
        return json.dumps({
            "success": False,
            "error": f"Analysis failed: {str(e)}",
        })


