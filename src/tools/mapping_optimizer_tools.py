def check_ontop_container_health(dataset: str) -> dict:
    """
    Check OnTop container health and extract error messages from logs if unhealthy.

    This function checks if the container is running properly or stuck in a restart loop,
    and extracts relevant error messages from the logs (especially mapping errors).

    When USE_SLOT_CONTAINERS is enabled and a slot_id is set in context,
    checks the slot-specific container instead of the shared one.

    Args:
        dataset: Dataset ID (e.g., "trn-large", "edu")

    Returns:
        Dict with:
        - healthy: True/False
        - status: Container status (running, restarting, exited, etc.)
        - error_message: Extracted error if unhealthy (especially mapping errors)
        - error_type: Type of error (mapping_error, startup_error, unknown)
        - slot_id: The slot ID if using slot containers
    """
    import re
    import time

    try:
        import docker
        client = docker.from_env()

        # Check for slot-based container naming
        slot_id = get_slot_id()

        # Build the full dataset name with size suffix if needed
        SIZED_DATASETS = {"edu", "trn", "nrg"}
        base_dataset = dataset.lower().replace('-small', '').replace('-large', '').replace('_small', '').replace('_large', '')
        has_size = any(s in dataset.lower() for s in ['-small', '-large', '_small', '_large'])

        if base_dataset in SIZED_DATASETS and not has_size:
            size = get_dataset_size()
            full_dataset = f"{base_dataset}-{size}"
        else:
            full_dataset = dataset

        base_name = full_dataset.replace('-', '_')

        if USE_SLOT_CONTAINERS and slot_id is not None:
            container_name = f"ontop_{base_name}_slot{slot_id}"
        else:
            container_name = f"ontop_{base_name}"

        try:
            container = client.containers.get(container_name)
        except docker.errors.NotFound:
            return {
                "healthy": False,
                "status": "not_found",
                "error_message": f"Container not found: {container_name}",
                "error_type": "container_not_found",
            }

        # Check container status
        container.reload()
        status = container.status

        # Check if container is in restart loop
        if "restarting" in status.lower():
            # Get logs to find the error
            logs = container.logs(tail=100).decode("utf-8", errors="ignore")

            # Extract mapping error
            error_msg, error_type = _extract_ontop_error(logs)

            return {
                "healthy": False,
                "status": "restarting",
                "error_message": error_msg,
                "error_type": error_type,
            }

        # Container is running - verify SPARQL endpoint works
        if status == "running":
            endpoint = get_endpoint_for_dataset(dataset)
            if endpoint:
                try:
                    with httpx.Client(timeout=5) as http_client:
                        response = http_client.get(
                            endpoint,
                            params={"query": "ASK { ?s ?p ?o } LIMIT 1"},
                            headers={"Accept": "application/sparql-results+json"},
                        )
                        if response.status_code == 200:
                            return {
                                "healthy": True,
                                "status": "running",
                                "error_message": None,
                                "error_type": None,
                            }
                except Exception:
                    pass

            # SPARQL endpoint not responding - check logs
            logs = container.logs(tail=100).decode("utf-8", errors="ignore")
            error_msg, error_type = _extract_ontop_error(logs)

            return {
                "healthy": False,
                "status": "running_but_unhealthy",
                "error_message": error_msg or "SPARQL endpoint not responding",
                "error_type": error_type or "endpoint_error",
            }

        return {
            "healthy": False,
            "status": status,
            "error_message": f"Container in unexpected state: {status}",
            "error_type": "unknown",
        }

    except ImportError:
        return {
            "healthy": False,
            "status": "unknown",
            "error_message": "docker package not installed",
            "error_type": "dependency_error",
        }
    except Exception as e:
        return {
            "healthy": False,
            "status": "unknown",
            "error_message": str(e),
            "error_type": "unknown",
        }


def _extract_ontop_error(logs: str) -> tuple[str | None, str | None]:
    """
    Extract OnTop error messages from container logs.

    Returns:
        Tuple of (error_message, error_type)
    """
    import re

    # Pattern for InvalidMappingSourceQueriesException
    mapping_error_pattern = r"InvalidMappingSourceQueriesException:\s*(.+?)(?:\n|$)"
    match = re.search(mapping_error_pattern, logs, re.DOTALL)
    if match:
        # Get the full error including the mapping details
        error_start = match.start()
        # Find the mapping assertion details
        mapping_assertion_pattern = r"\[id:\s*mapping-\d+.*?source query:.*?\]"
        assertion_match = re.search(mapping_assertion_pattern, logs[error_start:], re.DOTALL)
        if assertion_match:
            full_error = match.group(1).strip()
            # Add the mapping assertion for context
            full_error += "\n" + assertion_match.group(0)
            return full_error, "mapping_error"
        return match.group(1).strip(), "mapping_error"

    # Pattern for other repository errors
    repo_error_pattern = r"RepositoryException:\s*(.+?)(?:\n|$)"
    match = re.search(repo_error_pattern, logs)
    if match:
        return match.group(1).strip(), "repository_error"

    # Pattern for SQL errors
    sql_error_pattern = r"SQLException:\s*(.+?)(?:\n|$)"
    match = re.search(sql_error_pattern, logs)
    if match:
        return match.group(1).strip(), "sql_error"

    # Generic exception
    exception_pattern = r"Exception.*?:\s*(.+?)(?:\n|$)"
    match = re.search(exception_pattern, logs)
    if match:
        return match.group(1).strip(), "startup_error"

    return None, None


