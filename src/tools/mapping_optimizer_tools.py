def _get_database_name(dataset: str) -> str:
    """Map dataset ID to MySQL database name.

    Reads the database name from the dataset's ontop.properties JDBC URL,
    which is the single source of truth for the database connection.

    Falls back to convention-based naming if the properties file is not found.
    """
    # Try to read from ontop.properties (single source of truth)
    import re
    props_path = MAPPINGS_DIR_ROOT / dataset.lower() / "ontop.properties"
    if props_path.exists():
        try:
            text = props_path.read_text(encoding="utf-8")
            match = re.search(r"jdbc\.url=jdbc:mysql://[^/]+/(\w+)", text)
            if match:
                return match.group(1)
        except Exception:
            pass

    # Fallback: convention-based naming
    return dataset.lower().replace("-", "_")


