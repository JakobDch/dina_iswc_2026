"""
Mapping Optimizer Agent for Dynamic R2RML Mapping Optimization.

This agent is invoked by the SPARQL Agent when a query times out due to
self-joins caused by inefficient IRI templates in the R2RML mapping.

The agent:
1. Analyzes the IRI template for the problematic table
2. Gets the primary key columns from the database
3. Suggests an optimized template using PK columns
4. Applies the change and restarts OnTop
5. Provides detailed reasoning for all decisions

Workflow:
1. Receive query and SQL analysis from SPARQL Agent
2. For each self-join table:
   a. Get primary key columns
   b. Analyze current IRI template
   c. Suggest optimized template
   d. Apply the change
3. Verify mapping syntax
4. Restart OnTop container
5. Return detailed result with reasoning
"""

