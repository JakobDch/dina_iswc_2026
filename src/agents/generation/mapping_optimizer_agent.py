    def _get_sql_diagnosis(self, generated_sql: str) -> str:
        """Pre-compute SQL analysis using sqlglot. Returns formatted diagnosis text."""
        try:
            from src.tools.sql_analyzer import analyze_sql

            analysis = analyze_sql(generated_sql)

            lines = ["## SQL Diagnosis (pre-computed)"]

            if analysis.has_self_join:
                for table, aliases in analysis.self_joins.items():
                    lines.append(f"- **Self-join detected**: `{table}` appears {len(aliases)}x (aliases: {', '.join(aliases)})")
            else:
                lines.append("- No self-joins detected in SQL")

            if analysis.union_branch_count > 1:
                lines.append(f"- **UNION branches**: {analysis.union_branch_count}")

            if analysis.join_conditions:
                lines.append("- **JOIN conditions**:")
                for jc in analysis.join_conditions:
                    lines.append(f"  - `{jc.left_table}.{jc.left_column}` = `{jc.right_table}.{jc.right_column}`")

            lines.append(f"- **Tables referenced**: {', '.join(analysis.tables)}")

            return '\n'.join(lines)
        except Exception as e:
            logger.debug(f"SQL diagnosis failed (non-critical): {e}")
            return ""

