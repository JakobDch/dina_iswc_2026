    def _extract_json_from_text(self, text: str) -> dict | None:
        """Extract JSON object from text that may contain other content.

        Tries multiple strategies:
        1. Look for JSON in markdown code blocks (```json ... ```)
        2. Find the largest valid JSON object by trying all { positions
        """
        import re

        # Strategy 1: Look for JSON in markdown code blocks
        code_block_pattern = r'```(?:json)?\s*(\{[\s\S]*?\})\s*```'
        matches = re.findall(code_block_pattern, text)
        for match in matches:
            try:
                return json.loads(match)
            except json.JSONDecodeError:
                continue

        # Strategy 2: Find all { positions and try to parse from each
        # Start from the end (most likely to be the final JSON response)
        brace_positions = [i for i, c in enumerate(text) if c == '{']

        for start_pos in reversed(brace_positions):
            # Find matching closing brace by counting
            depth = 0
            end_pos = start_pos
            for i, c in enumerate(text[start_pos:], start=start_pos):
                if c == '{':
                    depth += 1
                elif c == '}':
                    depth -= 1
                    if depth == 0:
                        end_pos = i + 1
                        break

            if end_pos > start_pos:
                try:
                    candidate = text[start_pos:end_pos]
                    parsed = json.loads(candidate)
                    # Verify it looks like our expected response format
                    if isinstance(parsed, dict) and ("status" in parsed or "success" in parsed):
                        return parsed
                except json.JSONDecodeError:
                    continue

        return None

    def _parse_response(self, messages: list[BaseMessage]) -> MappingOptimizerResult:
        """Parse the final agent response into a MappingOptimizerResult."""
        # Find the final AI message without tool calls
        final_response = ""
        for msg in reversed(messages):
            if isinstance(msg, AIMessage) and msg.content and not msg.tool_calls:
                final_response = normalize_content(msg.content)
                break

        if not final_response:
            return MappingOptimizerResult(
                success=False,
                can_help=True,  # Unknown, assume could help
                error="No final response from agent",
                reasoning="Agent did not produce a final response after tool calls",
            )

        # Try to extract JSON from response (handles markdown, extra text, etc.)
        result_json = self._extract_json_from_text(final_response)

        if result_json:
            status = result_json.get("status", "")

            if status == "SUCCESS":
                # Parse changes
                changes = []
                for change in result_json.get("changes_made", []):
                    changes.append(MappingChange(
                        table=change.get("table", ""),
                        old_template=change.get("old_template", ""),
                        new_template=change.get("new_template", ""),
                        primary_key_columns=change.get("primary_key_columns", []),
                        old_template_columns=change.get("old_template_columns", []),
                        sql_before=change.get("sql_before"),
                        sql_after=change.get("sql_after"),
                    ))

                # Derive optimized_tables from changes if LLM didn't provide it
                optimized_tables = result_json.get("optimized_tables", [])
                if not optimized_tables and changes:
                    optimized_tables = list({c.table for c in changes if c.table})
                # Last resort: if we have changes but no table names, mark as "mapping_modified"
                if not optimized_tables and changes:
                    optimized_tables = ["mapping_modified"]

                return MappingOptimizerResult(
                    success=True,
                    can_help=True,
                    optimized_tables=optimized_tables,
                    changes_made=changes,
                    requires_restart=len(changes) > 0,  # Signal restart needed if changes were made
                    reasoning=result_json.get("reasoning", ""),
                    identified_issues=result_json.get("identified_issues", []),
                )

            elif status == "CANNOT_HELP":
                # Agent determined mapping optimization won't help
                return MappingOptimizerResult(
                    success=True,  # Agent worked correctly
                    can_help=False,  # But can't help with this issue
                    reasoning=result_json.get("reasoning", ""),
                    analysis=result_json.get("analysis", ""),
                )

            else:  # FAILED or unknown
                return MappingOptimizerResult(
                    success=False,
                    can_help=result_json.get("can_help", True),
                    error=result_json.get("error", "Unknown error"),
                    reasoning=result_json.get("reasoning", ""),
                )

        # Could not extract valid JSON
        return MappingOptimizerResult(
            success=False,
            can_help=True,  # Unknown, assume could help
            error="Could not parse agent response as JSON",
            reasoning=final_response[:500],
        )


